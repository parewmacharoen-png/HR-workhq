export function greetingForHour(name: string, hour = new Date().getHours()): string {
  const prefix =
    hour < 12
      ? th.dashboard.greetingMorning
      : hour < 17
        ? th.dashboard.greetingAfternoon
        : th.dashboard.greetingEvening;
  return `${prefix}, คุณ${name} 👋`;
}

export function employmentStatusLabel(status: string): string {
  return th.employmentStatus[status] ?? status;
}

export function absenceStatusLabel(status: string): string {
  return th.absenceStatus[status] ?? status;
}

export function probationStatusLabel(code: string | null | undefined): string {
  if (!code) return th.common.dash;
  return th.probationStatus[code] ?? code;
}

export function employmentTypeLabel(type: string | null | undefined): string {
  if (!type) return '';
  return th.employmentType[type] ?? type;
}

export function workCategoryLabel(category: string | null | undefined): string {
  if (!category) return th.common.dash;
  return th.workCategory[category] ?? category.toUpperCase();
}

export function roleLabel(code: string | null | undefined): string {
  if (!code) return th.roles.employee;
  const key = code.toLowerCase().replace(/\s+/g, '_');
  return th.roles[key] ?? code.replace(/_/g, ' ');
}

export function userRoleLabel(roles: string[]): string {
  if (!roles.length) return th.roles.employee;
  const first = roles[0].toLowerCase();
  return th.roles[first] ?? roles.join(', ');
}

export function disciplinaryActionTypeLabel(type: string): string {
  return th.employeeDisciplinary.actionTypes[type as keyof typeof th.employeeDisciplinary.actionTypes] ?? type;
}

export function adminCommissionOfficeTypeLabel(type: string | null | undefined): string {
  if (type === 'back_office') return th.adminCommission.officeTypeBack;
  if (type === 'front_office') return th.adminCommission.officeTypeFront;
  return type ?? '—';
}
